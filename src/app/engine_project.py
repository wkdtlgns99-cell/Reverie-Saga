"""Deterministic generation of the sample catalog and C# protocol DTOs."""

from __future__ import annotations

import argparse
from dataclasses import asdict, fields
import hashlib
from pathlib import Path
from typing import Sequence, cast

from adapters.narrative_catalog import compile_catalog, decode_catalog
from app.engine_bridge import REQUEST_FIELDS, RESPONSE_FIELDS, SCHEMA_HASH
from contracts.client import ClientUpdate, ClientView
from contracts.narratives import Narrative, NarrativeCategory
from domain.canonical import (
    JsonObject,
    array_value,
    canonical_json,
    decode_json,
    object_value,
    seal,
    text_value,
)


def _class(name: str, members: tuple[tuple[str, str], ...]) -> str:
    return (
        "[Serializable]\npublic sealed class "
        + name
        + " {\n"
        + "".join(f"    public {kind} {field};\n" for field, kind in members)
        + "}\n"
    )


def wire_csharp_type(annotation: str) -> str:
    mapping = {
        "str": "string",
        "NarrativeCategory": "string",
        "int": "string",
        "bool": "bool",
        "tuple[int, ...]": "string[]",
        "tuple[str, ...]": "string[]",
        "ClientView | None": "WireView",
        "ClientUpdate": "WireUpdate",
        "tuple[Narrative, ...]": "WireNarrative[]",
    }
    try:
        return mapping[annotation]
    except KeyError as error:
        raise ValueError("WIRE_ANNOTATION:" + annotation) from error


def generate_wire() -> str:
    view = tuple((f.name, wire_csharp_type(str(f.type))) for f in fields(ClientView))
    update = tuple((f.name, wire_csharp_type(str(f.type))) for f in fields(ClientUpdate))
    narrative = tuple((f.name, wire_csharp_type(str(f.type))) for f in fields(Narrative))
    return (
        "// Generated by python -m app.engine_project;do not edit DTOs.\n"
        "using System;\nnamespace ReverieSaga {\n"
        + _class("WireView", view)
        + _class("WireUpdate", update)
        + _class("WireNarrative", narrative)
        + _class("WireResponse", tuple((name, wire_csharp_type(t)) for name, t in RESPONSE_FIELDS))
        + _class("WireRequest", tuple((f, "string") for f in REQUEST_FIELDS))
        + f'public static class WireSchema {{ public const string Hash = "{SCHEMA_HASH}"; }}\n'
        + "}\n"
    )


def build_sample(root: Path) -> tuple[bytes, bytes]:
    dossier_path = root / "docs/reference/QUILLTALE_CONTENT_CANDIDATES.json"
    dossier_bytes = dossier_path.read_bytes()
    approval = root / "docs/reviews/QT-F04_GENERATION_EVIDENCE_2026-10-12.json"
    qualification = object_value(decode_json(approval.read_bytes()))
    if hashlib.sha256(dossier_bytes).hexdigest() != text_value(
        qualification["candidate_dossier_sha256"]
    ):
        raise ValueError("NARRATIVE_DOSSIER_UNQUALIFIED")
    dossier = object_value(decode_json(dossier_bytes))
    if (
        qualification["record_type"] != "scoped_generation_and_terms_qualification"
        or qualification["decision_scope"]
        != "six named existing selections only;future narrative adaptation eligibility;no blanket corpus/legal/import/release approval"
        or qualification["source_commit"] != dossier["source_commit"]
    ):
        raise ValueError("NARRATIVE_QUALIFICATION")
    qualified_rows: dict[str, JsonObject] = {}
    for value in array_value(object_value(qualification["inspection"])["rows"]):
        approved_row = object_value(value)
        candidate_id = text_value(approved_row["candidate_id"])
        if (
            candidate_id in qualified_rows
            or approved_row["qualification"] != "QUALIFIED_FOR_FUTURE_NARRATIVE_ADAPTATION"
        ):
            raise ValueError("NARRATIVE_QUALIFICATION")
        qualified_rows[candidate_id] = approved_row
    dossier_rows = tuple(object_value(r) for r in array_value(dossier["entries"]))
    ids = tuple(text_value(r["candidate_id"]) for r in dossier_rows)
    if len(ids) != 6 or len(set(ids)) != 6 or set(ids) != set(qualified_rows):
        raise ValueError("NARRATIVE_QUALIFICATION")

    categories = {
        "settlement_concept": "settlement",
        "facility_concept": "facility",
        "quest_premise": "quest",
        "creature_visual_concept": "creature",
    }
    entries: list[Narrative] = []
    evidence: list[dict[str, str]] = []
    for row in dossier_rows:
        candidate = text_value(row["candidate_id"])
        approved_row = qualified_rows[candidate]
        for key in ("source_path", "source_entry_id"):
            if approved_row[key] != row[key]:
                raise ValueError("NARRATIVE_QUALIFICATION")
        if (
            approved_row["source_commit"] != dossier["source_commit"]
            or set(object_value(approved_row["source_fields"]))
            != set(text_value(v) for v in array_value(row["source_fields"]))
            or hashlib.sha256(canonical_json(approved_row["source_fields"])).hexdigest()
            != approved_row["selected_fields_sha256"]
            or approved_row["adapted_name"] != row["name_ko"]
            or approved_row["adapted_description"] != row["description_ko"]
        ):
            raise ValueError("NARRATIVE_QUALIFICATION")
        category = cast(NarrativeCategory, categories[text_value(row["category"])])
        entry_id = f"narrative:{category}-" + hashlib.sha256(candidate.encode()).hexdigest()[:16]
        entry = Narrative(
            entry_id, category, text_value(row["name_ko"]), text_value(row["description_ko"])
        )
        entries.append(entry)
        evidence.append(
            {
                "entry_id": entry_id,
                "candidate_id": candidate,
                "source_path": text_value(row["source_path"]),
                "source_entry_id": text_value(row["source_entry_id"]),
                "source_commit": text_value(dossier["source_commit"]),
                "adapted_sha256": hashlib.sha256(canonical_json(seal(asdict(entry)))).hexdigest(),
                "qualification": text_value(approved_row["qualification"]),
                "qualification_evidence_sha256": hashlib.sha256(approval.read_bytes()).hexdigest(),
                "use": "descriptive_client_display_only",
            }
        )
    body = compile_catalog(tuple(entries))
    digest = hashlib.sha256(body).hexdigest()
    if decode_catalog(body, digest) != tuple(sorted(entries, key=lambda e: e.entry_id)):
        raise ValueError("CATALOG_GENERATION_MISMATCH")
    manifest = canonical_json(
        seal(
            {
                "format": "reverie-narrative-manifest/v1",
                "catalog_path": "narratives.json",
                "catalog_sha256": digest,
                "source_dossier_sha256": hashlib.sha256(
                    (root / "docs/reference/QUILLTALE_CONTENT_CANDIDATES.json").read_bytes()
                ).hexdigest(),
                "import_authority": "QT-F06 director resume 2026-10-12;distinct from source qualification",
                "source_qualification_scope": text_value(qualification["decision_scope"]),
                "entries": sorted(evidence, key=lambda e: e["entry_id"]),
            }
        )
    )
    return body, manifest


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path.cwd())
    args = parser.parse_args(argv)
    body, manifest = build_sample(args.root)
    wire_source = generate_wire()
    content = args.root / "content"
    content.mkdir(exist_ok=True)
    for name, data in (("narratives.json", body), ("narratives.manifest.json", manifest)):
        target = content / name
        pending = target.with_suffix(target.suffix + ".pending")
        pending.write_bytes(data)
        pending.replace(target)
    scripts = args.root / "clients/unity/Assets/Reverie/Scripts"
    scripts.mkdir(parents=True, exist_ok=True)
    (scripts / "Wire.Generated.cs").write_text(wire_source, encoding="utf-8")
    (scripts / "CatalogPin.Generated.cs").write_text(
        "// Generated;actual narrative bytes must match this pin.\n"
        f"namespace ReverieSaga {{ public static class CatalogPin {{ public const string Hash = "
        f'"{hashlib.sha256(body).hexdigest()}"; }} }}\n',
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
